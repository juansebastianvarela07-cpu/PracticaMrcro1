#include <xc.inc>
;--- BITS DE CONFIGURACION---
    CONFIG FOSC = INTOSCIO_EC  ; OSCILADOR INTERNO
    CONFIG WDT = OFF           ; WATCHDOG TIMER APAGADO
    CONFIG LVP = OFF           ; PROGRAMACION EN BAJO VOLTAJE APAGADA
    CONFIG PBADEN = OFF        ; PINES DE PORTB COMO DIGITALES
    CONFIG MCLRE = OFF         ; PIN MCLR DESHABILITADO
    CONFIG XINST = OFF         ; MODO DE INSTRUCCIONES EXTENDIDAS DESACTIVADO

;========================================================================
; VARIABLES EN MEMORIA RAM
;========================================================================
PSECT udata_acs

    ;===== BANDERAS DE ESTADO (BOOLEANAS) ======
    ESTADO_ALARMA:     DS 1 ; 0 = APAGADA, 1 = ENCENDIDA (INT0)
    ESTADO_VENTILADOR: DS 1 ; 0 = APAGADO, 1 = ENCENDIDO (INT1)
    MODO_UNIDAD:       DS 1 ; 0 = °CELSIUS, 1 = °FAHRENHEIT (INT2)

    ;===== DATOS DEL ADC Y CONVERSION ======
    VALOR_ADC_L:       DS 1 ; BYTE BAJO DE LA LECTURA DEL ADC
    VALOR_ADC_H:       DS 1 ; BYTE ALTO DE LA LECTURA DEL ADC
    TEMP_CELSIUS:      DS 1 ; VALOR CONVERTIDO EN °C
    TEMP_FAHRENHEIT:   DS 1 ; VALOR CONVERTIDO EN °F
    TEMP_MOSTRAR:      DS 1 ; VALOR FINAL PARA ENVIAR AL DISPLAY

    ;===== BCD PARA EL DISPLAY 7 SEGMENTOS ======
    DIGITO_DEC:        DS 1 ; DECENAS (0-9) PARA EL DISPLAY
    DIGITO_UNID:       DS 1 ; UNIDADES (0-9) PARA EL DISPLAY

    ;===== CONTADORES Y CONTROL DE TIEMPO ======
    CONTADOR_ADC:      DS 1 ; TEMPORIZADOR SECUNDARIO PARA LANZAR LA LECTURA
    DIGITO_ACTUAL:     DS 1 ; BANDERA PARA ALTERNAR EL MULTIPLEXADO DE LOS DISPLAYS (NUEVO)
    ;====== PATRON PARA LOS DISPLAYS =======
    PATRON_DEC:        DS 1 ; LEDS DE LAS DECENAS DECODIFICADOS
    PATRON_UNID:       DS 1 ; LEDS DE LAS UNIDADES DECODIFICADOS

    ;===== BANDERAS DE CONTROL GENERAL ======
    PEDIR_ADC:        DS 1 ; BANDERA: 1 CUANDO TIMER0 AUTORIZA LEER EL SENSOR
    ACTUALIZAR:       DS 1 ; BANDERA: 1 CUANDO SE ACTUALIZA EÑ DISPLAY

    ;===== VARIABLES TEMPORALES PARA OPERACIONES ======
    MATH_TEMP:        DS 1 ; VARIABLE TEMPORAL PARA MATEMATICAS Y RESTAS

    ;===== DELAYS PARA LOS DISPLAYS =======
    INDICE:           DS 1 ; INDICE PARA TABLA DE DECODIFICACIÓN
    VALOR:            DS 1 ; VALOR TEMPORAL PARA CÁLCULOS
    DECENAS:          DS 1 ; DECENAS TEMPORALES
    UNIDADES:         DS 1 ; UNIDADES TEMPORALES
    TEMP4:            DS 1 ; VARIABLE AUXILIAR PARA CÁLCULOS
    RESTO:            DS 1 ; RESTO DE DIVISIÓN
    COCIENTE:         DS 1 ; COCIENTE DE DIVISIÓN
;===============================================
; VECTOR DE RESET
;===============================================
PSECT resetVec, class=CODE, reloc=2
ORG    0x0000
GOTO   INICIO           ; SALTA A LA ETIQUETA INICIO AL ARRANCAR

;===============================================
; VECTOR DE INTERRUPCION
;===============================================
PSECT intVec, class=CODE, reloc=2
ORG    0x0008
GOTO   RUTINA_ISR        ; SALTA A LAS INTERRUPCIONES SI OCURRE UN EVENTO

    
;================================================
; RUTINA DE INTERRUPCIONES (SALTOS AL OCURRIR EVENTOS EXTERNOS O DEL TIMER)
;================================================    
PSECT main_code, class=CODE, reloc=2
RUTINA_ISR:
    
; ======= INT0 - LED ALARMA ============
    BTFSS   INTCON, 1, a      ; ¿SE ACTIVO LA BANDERA DE INT1?
    GOTO    ISR_INT1
    BTG     LATC,0, a         ; INVIERTE ESTADO FISICO DEL LED (RC0)
    BTG     ESTADO_ALARMA, 0, a ;  INVIERTE ESTADO EN RAM
    BCF     INTCON, 1, a      ;  LIMPIA BANDERA DE INT0

ISR_INT1:
; ======= INT1 - VENTILADOR ============
    BTFSS   INTCON3, 0, a     ; SE ACTIVO BANDERA INT1?
    GOTO    ISR_INT2   
    BTG     LATC, 1, a        ; INVIERTE EL ESTADO DEL TRANSISTOR (RC1)
    BTG     ESTADO_VENTILADOR, 0, a ; INVIERTE ESTADO EN LA RAM
    BCF     INTCON3, 0, a      ; LIMPIA LA BANDERA DE INT1

ISR_INT2:
; ======= INT2 - BOTON C/F  ============
    BTFSS   INTCON3, 1, a     ; SE ACTIVO LA BANDERA INT2?
    GOTO    ISR_TMR0 
    BTG     MODO_UNIDAD, 0, a ; CAMBIA ENTRE 0(°C) y 1(°F)
    BSF     ACTUALIZAR, 0, a  ; AVISA REFRESCO DEL DISPLAY
    BCF     INTCON3, 1, a     ; LIMPIA LA BANDERA DEL INT2

ISR_TMR0:
    BTFSS   INTCON, 2, a      ; SE DESBORDO EL TIMER0?
    GOTO    FIN_ISR
    ; RECARGAR TIMER0 PARA MULTIPLEXADO RAPIDO
    MOVLW   0xFF
    MOVWF   TMR0H, 0         ; PRECARGA EL BYTE ALTO PARA AJUSTAR LA VELOCIDAD DE INTERRUPCION
    MOVLW   0x06
    MOVWF   TMR0L, a         ; PRECARGA EL BYTE BAJO DEL TIMER0
    BCF     INTCON, 2, a     ; LIMPIA LA BANDERA DEL TIMER0
    
    ; LLAMAR AL MULTIPLEXADO
    CALL    MULTIPLEXAR      ; LLAMA A LA FUNCION QUE ALTERNA LOS DISPLAYS
    ; CONTADOR PARA NO LEER ADC TAN RAPIDO 
    DECFSZ  CONTADOR_ADC, F, a
    GOTO    FIN_ISR
    
    MOVLW   20              ; RECARGAR CONTADOR
    MOVWF   CONTADOR_ADC, a
    BSF     PEDIR_ADC, 0, a  ; LEVANTA BANDERA PARA QUE EL BUCE LEA EL SENSOR
    
FIN_ISR:
    RETFIE  1                ; TERMINA LA INTERRUPCIÓN
    
    
;===============================================
; PROGRAMA PRINCIPAL
;===============================================

INICIO:
    ; ============================================================
    ;  CONFIGURAR EL OSCILADOR INTERNO A 8MHZ
    ; ============================================================
    BCF     RCON, 7, a        ; DESHABILITAR PRIORIDAD DE INTERRUPCIONES
    MOVLW   01110010B         ; CARGA EL LITERAL EN W (IRCF=111 PARA 8MHZ, SCS=10 PARA INTERNO)
    MOVWF   OSCCON, a         ; ESCRIBE W EN EL REGISTRO OSCCON
    
    CLRF    LATA, a           ; LIMPIA EL REGISTRO LATCH DEL PUERTO A PARA INICIAR APAGADO
    CLRF    LATC, a           ; LIMPIA EL REGISTRO LATCH DEL PUERTO C PARA INICIAR APAGADO
    CLRF    LATD, a           ; LIMPIA EL REGISTRO LATCH DEL PUERTO D PARA INICIAR APAGADO
     
    ; ============================================================
    ; CONFIGURACION DE PUERTOS 
    ; ============================================================
    ; PUERTOS A
    BSF   TRISA, 0, a          ; RA0: ENTRADA ANALOGICA (LM35)
    BCF   TRISA, 1, a          ; RA1: SALIDA (TRANSISTOR DECENAS)
    ; PUERTOS B
    BSF     TRISB, 0, a       ; RB0: ENTRADA (BOTON ALARMA)
    BSF     TRISB, 1, a       ; RB1: ENTRADA (BOTON VENTILADOR)
    BSF     TRISB, 2, a       ;RB2: ENTRADA (BOTON C/F)
    ; PUERTOS C
    BCF     TRISC, 0, a       ; RC0: SALIDA (LED ALARMA)
    BCF     TRISC, 1, a       ; RC1: SALIDA (TRANSISTOR VENTILADOR)
    BCF     TRISC, 2, a       ; RC2: SALIDA (TRANSISTOR UNIDADES)
    
    MOVLW   10000000B        
    MOVWF   TRISD, a          ; RD0-RD6: SALIDAS PARA LOS 7 SEGMENTOS  
    
    MOVLW   00000111B
    MOVWF   CMCON, a          ; APAGAR COMPARADORES
    
    BSF     TRISA, 0, a       ; PIN RA0 CONFIGURADO COMO ENTRADA
    ; === CONFIGURACION DEL CONVERSOR ANALOGO-DIGITAL (ADC) ===
    MOVLW   00001110B         
    MOVWF   ADCON1, a         ; ASIGNA UNICAMENTE AN0 COMO ANALOGO, RESTO COMO DIGITALES
    MOVLW   00010010B         
    MOVWF   ADCON2, a         ; JUSTIFICA EL RESULTADO A LA IZQUIERDA Y CONFIGURA LOS TIEMPOS
    MOVLW   00000001B         
    MOVWF   ADCON0, a         ; SELECCIONA EL CANAL AN0 Y ENCIENDE ELECTRICAMENTE EL MODULO ADC

    ; ============================================================
    ; INICIALIZACION DE VARIABLES A 0
    ; ============================================================
    CLRF    ESTADO_ALARMA, a     ; INICIA LA ALARMA APAGADA (0)
    CLRF    ESTADO_VENTILADOR, a ; INICIA EL VENTILADOR APAGADO (0)
    CLRF    MODO_UNIDAD, a       ; INICIA EL MODO EN CELSIUS (0)
    CLRF    PEDIR_ADC, a         ; BAJA LA BANDERA DE LECTURA DEL SENSOR AL ARRANCAR
    CLRF    ACTUALIZAR, a        ; BAJA LA BANDERA DE ACTUALIZACION DE PANTALLA AL ARRANCAR 
    CLRF    DIGITO_ACTUAL, a     ; REINICIA EL ALTERNADOR PARA QUE EL MULTIPLEXADO INICIE EN ORDEN
    CLRF    TEMP_CELSIUS, a      ; BORRA CUALQUIER DATOS BASURA EN LA TEMPERATURA CELSIUS
    CLRF    TEMP_FAHRENHEIT, a   ; BORRA CUALQUIER DATOS BASURA EN LA TEMPERATURA FAHRENHEIT
    CLRF    VALOR, a             ; VACIA EL REGISTRO TEMPORAL ANTES DEL PRIMER CALCULO
    CLRF    DECENAS, a           ; ASEGURA QUE EL CONTADOR DE DECENAS INICIE EN CERO
    CLRF    UNIDADES, a          ; ASEGURA QUE EL CONTADOR DE UNIDADES INICIE EN CERO
    CLRF    TEMP4, a             ; LIMPIA LA VARIABLE AUXILIAR DE MULTIPLICACION
    CLRF    RESTO, a             ; LIMPIA EL RESIDUO DE LA DIVISION MATEMATICA
    CLRF    COCIENTE, a          ; LIMPIA EL RESULTADO ENTERO DE LA DIVISION
     
    MOVLW  00111111B
    MOVWF   PATRON_DEC, a     ; PRECARGA EL PATRON DEL NUMERO CERO PARA LAS DECENAS
    MOVWF   PATRON_UNID, a    ; PRECARGA EL PATRON DEL NUMERO CERO PARA LAS UNIDADES 
    
    MOVLW   20
    MOVWF   CONTADOR_ADC, a; INICIALIZA EL MULTIPLICADOR DE TIEMPO DEL SENSOR
   
    ; ============================================================
    ;  CONFIGURACIÓN DEL TIMER0
    ; ============================================================
    MOVLW   00000011B         
    MOVWF   T0CON, a         ; CONFIGURA TIMER0 EN 16 BITS, RELOJ INTERNO Y PRESCALER DE 1:16
    MOVLW   0xFF 
    MOVWF   TMR0H, a         ; CARGA INICIAL DEL BYTE ALTO
    MOVLW   0x06          
    MOVWF   TMR0L, a         ; CARGA INICIAL DEL BYTE BAJO
    
    CLRF    INTCON, a        ; LIMPIA CONFIGURACIONES RESIDUALES DE INTERRUPCION GLOBAL
    CLRF    INTCON3, a       ; LIMPIA CONFIGURACIONES RESIDUALES DE INTERRUPCIONES SECUNDARIAS
    
    MOVLW  10000000B
    MOVWF  INTCON2, a        ; DESHABILITA PULL-UPS Y CONFIGURA FLANCOS DE BAJADA PARA LOS BOTONES

    ; HABILITAR LOS PERMISOS INDIVIDUALES DE INTERRUPCION
    BSF     INTCON, 4, a      ; HABILITA INT0 (ALARMA)
    BSF     INTCON3, 3, a     ; HABILITA INT1 (VENTILADOR)
    BSF     INTCON3, 4, a     ; HABILITA INT2 (GRADOS)
    BSF     INTCON, 5, a      ; HABILITA LA INTERRUPCION DEL TIMER0
    BSF     T0CON, 7, a       ; ENCIENDE OFICIALMENTE EL MODULO TIMER0
    BSF     INTCON, 7, a      ; ENCIENDE EL INTERRUPTOR GLOBAL DE INTERRUPCIONES (GIE)

    BSF     PEDIR_ADC, 0, a   ; LEVANTA LA BANDERA PARA FORZAR LA PRIMERA LECTURA AL ARRANCAR
;===============================================
; BUCLE PRINCIPAL (SE EJECUTA INFINITAMENTE)
;===============================================
LOOP_PRINCIPAL:

    BTFSC   PEDIR_ADC, 0, a   ; COMPRUEBA SI EL TIMER SOLICITO UNA LECTURA
    CALL    LEER_ADC          ; EJECUTA LA LECTURA SI LA BANDERA ESTA ARRIBA
    
    BTFSC   ACTUALIZAR, 0, a  ; COMPRUEBA SI SE SOLICITO ACTUALIZAR LOS DATOS DE PANTALLA
    CALL    PREPARAR_DISPLAY ; PROCESA LA NUEVA TEMPERATURA HACIA LOS DISPLAYS
    
    GOTO    LOOP_PRINCIPAL    ; CICLO INFINITO QUE SOLO ACTUA CUANDO LAS BANDERAS LO INDICAN
LEER_ADC:
  BCF     PEDIR_ADC, 0, a     ; BAJA LA BANDERA DE SOLICITUD DE ADC
  BSF     ADCON0, 1 ,a        ; ORDENA AL HADWAR INICIAR LA CONVERSIÓN
 
ESPERAR_ADC:
    BTFSC   ADCON0, 1, a      ; VERIFICA CONSTANTEMENTE SI EL BIT GO SE PUSO EN CERO
    GOTO    ESPERAR_ADC
   
    MOVF    ADRESH, W, a
    ADDWF   ADRESH, W, a      ; MULTIPLICA POR DOS SUMANDO EL REGISTRO CONSIGO MISMO
    MOVWF   TEMP_CELSIUS, a   ; ALMACENA EL RESULTADO DIRECTAMENTE COMO GRADOS CELSIUS
    
    BTFSC   ADRESL, 7, a      ; EVALUA EL BIT MAS ALTO DE LA PARTE BAJA PARA REDONDEO
    INCF    TEMP_CELSIUS, F, a; INCREMENTA EN UNO LA TEMPERATURA SI EL BIT ES UNO
    
    MOVLW   100
    SUBWF   TEMP_CELSIUS, W, a; RESTA 100 A LA TEMPERATURA CALCULADA
    BTFSS   STATUS, 0, a      ; EVALUA EL ACARREO PARA SABER SI SUPERO LOS 99 GRADOS
    GOTO    CELSIUS
    MOVLW   99                
    MOVWF   TEMP_CELSIUS, a   ; SI ES MAYOR O IGUAL A 100, FUERZA EL VALOR A 99 PARA EVITAR ERRORES DE DISPLAY

CELSIUS:
    CALL    CALCULAR_FAHRENHEIT        ; INICIA LA CONVERSION A FAHRENHEIT EN SEGUNDO PLANO
    BSF     ACTUALIZAR, 0, a  ; LEVANTA LA BANDERA ORDENANDO MOSTRAR EL RESULTADO
    RETURN
    
CALCULAR_FAHRENHEIT:
    MOVLW   38
    SUBWF   TEMP_CELSIUS, W, a 
    BTFSS   STATUS, 0, a 
    GOTO    HACER_F 
    MOVLW   99         
    MOVWF    TEMP_FAHRENHEIT, a ; SI CELSIUS SUPERA LOS 38, FAHRENHEIT SE FUERZA A 99
    RETURN
    
HACER_F:
    MOVF    TEMP_CELSIUS, W, a
    ADDWF   TEMP_CELSIUS, W, a 
    MOVWF   TEMP4, a    ; CREA UN MULTIPLO TEMPORAL EQUIVALENTE AL DOBLE DE CELSIUS

    MOVF    TEMP4, W, a
    ADDWF   TEMP4, W, a 
    MOVWF   RESTO, a          ; CREA UN MULTIPLO EQUIVALENTE AL CUADRUPLE DE CELSIUS

    CLRF    COCIENTE, a       ; INICIA EL CONTADOR DE LA DIVISION ENTERA EN CERO
DIV_5:
    MOVLW   5                 ; CARGA UN 5 EN W
    SUBWF   RESTO, W, a       ; RESTA 5 AL BMULTIPLO CREADO
    BTFSS   STATUS, 0, a      ; VERIFICA SI SE ALCANZO EL NUMERO NEGATIVO
    GOTO    FIN_DIV5         
    MOVWF   RESTO, a          ; ACTUALIZA EL SOBRANTE
    INCF    COCIENTE, F, a   ; SI ES POSITIVO, SUMA 1 AL COCIENTE
    GOTO    DIV_5          ; REPITE HASTA TERMINAR LA DIVISION

FIN_DIV5:
    MOVF    TEMP_CELSIUS, W, a
    ADDWF   COCIENTE, W, a    
    MOVWF   TEMP_FAHRENHEIT, a ; COMPLETA LA FORMULA (CELSIUS + 4/5 CELSIUS)
   
    MOVLW   32                 ; CARGA 32 EN W
    ADDWF   TEMP_FAHRENHEIT, F, a ; SUMA 32 AL RESULTADO DE LA DIVISION
    RETURN

PREPARAR_DISPLAY:
    BCF     ACTUALIZAR, 0, a  ; BAJA BANDERA DE ACTUALIZACIÓN VISUAL
    
    BTFSC   MODO_UNIDAD, 0, a ; COMPRUEBA SI EL USUARIO ELIGIO FAHRENHEIT (BIT 1)
    GOTO    U_F
    MOVF    TEMP_CELSIUS, W, a; MUEVE EL DATO DE CELSIUS AL REGISTRO DE TRABAJO
    GOTO    GUARDAR_VALOR

U_F: 
    MOVF    TEMP_FAHRENHEIT, W, a ; MUEVE EL DATO DE FAHRENHEIT AL REGISTRO DE TRABAJO 
    
GUARDAR_VALOR:
    MOVWF   VALOR, a          ; TRANSFIERE EL DATO ELEGIDO A LA VARIABLE GENERAL BCD
    CLRF    DECENAS, a        ; REINICIA EL CONTADOR DE DECENAS
    MOVF    VALOR, W, a
    MOVWF   UNIDADES, a       ; INICIALIZA LAS UNIDADES CON EL VALOR TOTAL PARA COMENZAR A RESTAR

BCD:
    MOVLW   10              ; CARGA UN 10 EN W
    SUBWF   UNIDADES, W, a  ; LE RESTA 10 AL TOTAL
    BNC     FIN_BCD         ; SI DA NEGATIVO SALTA AL FINAL DEL BCD
    MOVWF   UNIDADES, a     ; GUARDA LAS NUEVAS UNIDADES RESTANTES
    INCF    DECENAS, F, a   ; SUMA 1 A LAS DECENAS
    GOTO    BCD             ; REPITE LA RESTA

FIN_BCD:
    MOVF    DECENAS, W, a  
    MOVWF   MATH_TEMP, a       ;  GUARDAMOS LA DECENA PARA EL DECO
    CALL    DECODIFICADOR_7SEG ; BUSCA EL PATRON DE LUCES PARA EL NUMERO DE LAS DECENAS
    MOVWF   PATRON_DEC, a      ; ALMACENA EL PATRON DIBUJADO DE LAS DECENAS

    ; TRADUCIR NUMEROS SEPARADOS A PATRONES DE LUCES PARA EL DISPLAY
    MOVF   UNIDADES, W 
    MOVWF   MATH_TEMP, a       ; GUARDAMOS LA UNIDAD PARA EL DECO
    CALL    DECODIFICADOR_7SEG ; BUSCA EL PATRON DE LUCES PARA EL NUMERO DE LAS UNIDADES
    MOVWF   PATRON_UNID, a     ; ALMACENA EL PATRON DIBUJADO DE LAS UNIDADES
    RETURN
    
; === SUBRUTINA: MULTIPLEXAR LOS DISPLAYS ===
MULTIPLEXAR:
    BCF     LATA, 1, a        ; APAGA TRANSISTOR DE DECENAS (RA1)
    BCF     LATC, 2, a        ; APAGA TRANSISTOR DE UNIDADES (RC2)

    BTG     DIGITO_ACTUAL, 0, a ; ALTERNAR LA VARIABLE QUE DECIDE CUAL PRENDER

    BTFSC   DIGITO_ACTUAL, 0, a
    GOTO    MOSTRAR_UNIDADES
MOSTRAR_DEC: 
    MOVF    PATRON_DEC, W, a
    MOVWF   LATD, a           ; CARGA LOS BITS DE LA DECENA EN EL PUERTO D
    BSF     LATA, 1, a        ; ACTIVA EL TRANSISTOR DEL DISPLAY DE LAS DECENAS
    RETURN
MOSTRAR_UNIDADES:
    MOVF    PATRON_UNID, W, a
    MOVWF   LATD, a           ; CARGA LOS BITS DE LA UNIDAD EN EL PUERTO D
    BSF     LATC, 2, a        ; ACTIVA EL TRANSISTOR DEL DISPLAY DE LAS UNIDADES
    RETURN

;===============================================
; DECODIFICADOR 7 SEGMENTOS (TRADUCE UN NUMERO A BITS PARA LEDS)
;===============================================
DECODIFICADOR_7SEG:
    MOVLW   0                 ; CARGA 0 EN W
    SUBWF   MATH_TEMP, W, a   ; RESTA EL NUMERO QUE QUEREMOS TRADUCIR MENOS 0
    BTFSC   STATUS, 2, a      ; SI EL BIT Z (CERO) ES 1, EL NUMERO ERA 0
    RETLW   00111111B         ; RETORNA EL PATRON BINARIO PARA DIBUJAR EL '0'

    MOVLW   1
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   00000110B         ; RETORNA EL PATRON BINARIO PARA EL '1'

    MOVLW   2
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01011011B         ; RETORNA EL PATRON BINARIO PARA EL '2'

    MOVLW   3
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01001111B         ; RETORNA EL PATRON BINARIO PARA EL '3'

    MOVLW   4
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01100110B         ; RETORNA EL PATRON BINARIO PARA EL '4'

    MOVLW   5
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01101101B         ; RETORNA EL PATRON BINARIO PARA EL '5'

    MOVLW   6
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01111101B         ; RETORNA EL PATRON BINARIO PARA EL '6'

    MOVLW   7
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   00000111B         ; RETORNA EL PATRON BINARIO PARA EL '7'

    MOVLW   8
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01111111B         ; RETORNA EL PATRON BINARIO PARA EL '8'

    MOVLW   9
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01101111B         ; RETORNA EL PATRON BINARIO PARA EL '9'

    RETLW   00000000B         ; SI HAY ERROR O SOBREPASO, RETORNA APAGADO

    END