;========================================================================
; ARCHIVO:      PRACTICA1_CONTROLTEMPERATURA.ASM
; MICRO:        PIC18F4550 (XC8 PIC-AS)
; DESCRIPCION:  SISTEMA DE CONTROL Y SUPERVISION DE TEMPERATURA CON LM35,
;               ADC MUESTREADO POR TIMER0 E INTERRUPCIONES INT0, INT1, INT2.
;========================================================================

#include <xc.inc>
;--- BITS DE CONFIGURACION---
    CONFIG FOSC = INTOSCIO_EC  ; OSCILADOR INTERNO
    CONFIG WDT = OFF           ; WATCHDOG TIMER APAGADO
    CONFIG LVP = OFF           ; PROGRAMACION EN BAJO VOLTAJE APAGADA
    CONFIG PBADEN = OFF        ; PINES DE PORTB COMO DIGITALES
    CONFIG MCLRE = OFF         ; PIN MCLR DESHABILITADO
    CONFIG XINST = OFF         ; MODO DE INSTRUCCIONES EXTENDIDAS DESACTIVADO

;========================================================================
; VARIABLES EN MEMORIA RAM
;========================================================================
PSECT udata_acs

    ;===== BANDERAS DE ESTADO (BOOLEANAS) ======
    ESTADO_ALARMA:     DS 1 ; 0 = APAGADA, 1 = ENCENDIDA (INT0)
    ESTADO_VENTILADOR: DS 1 ; 0 = APAGADO, 1 = ENCENDIDO (INT1)
    MODO_UNIDAD:       DS 1 ; 0 = °CELSIUS, 1 = °FAHRENHEIT (INT2)

    ;===== DATOS DEL ADC Y CONVERSION ======
    VALOR_ADC_L:       DS 1 ; BYTE BAJO DE LA LECTURA DEL ADC
    VALOR_ADC_H:       DS 1 ; BYTE ALTO DE LA LECTURA DEL ADC
    TEMP_CELSIUS:      DS 1 ; VALOR CONVERTIDO EN °C
    TEMP_FAHRENHEIT:   DS 1 ; VALOR CONVERTIDO EN °F
    TEMP_MOSTRAR:      DS 1 ; VALOR FINAL PARA ENVIAR AL DISPLAY

    ;===== BCD PARA EL DISPLAY 7 SEGMENTOS ======
    DIGITO_DEC:        DS 1 ; DECENAS (0-9) PARA EL DISPLAY
    DIGITO_UNID:       DS 1 ; UNIDADES (0-9) PARA EL DISPLAY

    ;===== CONTADORES Y CONTROL DE TIEMPO ======
    CONTADOR_ADC:      DS 1 ; TEMPORIZADOR SECUNDARIO PARA LANZAR LA LECTURA

    ;====== PATRON PARA LOS DISPLAYS =======
    PATRON_DEC:        DS 1 ; LEDS DE LAS DECENAS DECODIFICADOS
    PATRON_UNID:       DS 1 ; LEDS DE LAS UNIDADES DECODIFICADOS

    ;===== BANDERAS DE CONTROL GENERAL ======
    FLAG_LEER_ADC:     DS 1 ; BIT 0: 1 CUANDO EL TIMER0 ORDENA LEER EL SENSOR

    ;===== VARIABLES TEMPORALES PARA OPERACIONES ======
    MATH_TEMP:         DS 1 ; VARIABLE TEMPORAL PARA MATEMATICAS Y RESTAS

    ;===== DELAYS PARA LOS DISPLAYS =======
    DELAY1:            DS 1 ; VARIABLE 1 PARA EL MICRO RETARDO DEL DISPLAY
    DELAY2:            DS 1 ; VARIABLE 2 PARA EL MICRO RETARDO DEL DISPLAY

;===============================================
; VECTOR DE RESET
;===============================================
PSECT resetVec, class=CODE, reloc=2
ORG    0x0000
GOTO   Inicio           ; SALTA A LA ETIQUETA INICIO AL ARRANCAR

;===============================================
; VECTOR DE INTERRUPCION
;===============================================
PSECT intVec, class=CODE, reloc=2
ORG    0x0008
GOTO   Rutina_ISR        ; SALTA A LAS INTERRUPCIONES SI OCURRE UN EVENTO

;===============================================
; PROGRAMA PRINCIPAL
;===============================================
PSECT main_code, class=CODE, reloc=2

Inicio:
    ; ============================================================
    ; SECCION 1: CONFIGURAR EL OSCILADOR INTERNO A 8MHZ
    ; ============================================================
    MOVLW   01110010B         ; CARGA EL LITERAL EN W (IRCF=111 PARA 8MHZ, SCS=10 PARA INTERNO)
    MOVWF   OSCCON, a         ; ESCRIBE W EN EL REGISTRO OSCCON

    ; ============================================================
    ; SECCION 2: INICIALIZACION DE VARIABLES RAM
    ; ============================================================
    CLRF    ESTADO_ALARMA, a     ; INICIA LA ALARMA APAGADA (0)
    CLRF    ESTADO_VENTILADOR, a ; INICIA EL VENTILADOR APAGADO (0)
    CLRF    MODO_UNIDAD, a       ; INICIA EL MODO EN CELSIUS (0)
    CLRF    FLAG_LEER_ADC, a     ; LIMPIA LA BANDERA DE LECTURA
    CLRF    PATRON_DEC, a        ; APAGA EL DATO DE LAS DECENAS
    CLRF    PATRON_UNID, a       ; APAGA EL DATO DE LAS UNIDADES

    ; ============================================================
    ; SECCION 3: CONFIGURACION DE PUERTOS E/S (TRIS Y LAT)
    ; ============================================================

    ; PUERTO D: SALIDAS PARA LOS SEGMENTOS DEL DISPLAY
    CLRF    TRISD, a          ; CONFIGURA TODO EL PUERTO D COMO SALIDA
    CLRF    LATD, a           ; PONE TODAS LAS SALIDAS DEL PUERTO D EN NIVEL BAJO (0V)

    ; PUERTO C: SALIDAS DE HABILITACION PARA LOS TRANSISTORES DE LOS DISPLAYS
    BCF     TRISC, 0, a       ; PIN RC0 (PIN 15) COMO SALIDA (TRANSISTOR DECENAS)
    BCF     TRISC, 1, a       ; PIN RC1 (PIN 16) COMO SALIDA (TRANSISTOR UNIDADES)
    CLRF    LATC, a           ; APAGA AMBOS TRANSISTORES PARA INICIAR

    ; PUERTO E: SALIDAS PARA ALARMA Y VENTILADOR
    BCF     TRISE, 0, a       ; PIN RE0 COMO SALIDA (LED ALARMA)
    BCF     LATE, 0, a        ; INICIA EL LED DE ALARMA APAGADO
    BCF     TRISE, 1, a       ; PIN RE1 COMO SALIDA (VENTILADOR)
    BCF     LATE, 1, a        ; INICIA EL VENTILADOR APAGADO

    ; PUERTO A: ENTRADA ANALOGICA PARA EL SENSOR LM35
    BSF     TRISA, 0, a       ; PIN RA0 CONFIGURADO COMO ENTRADA

    ; PUERTO B: ENTRADAS DIGITALES PARA LOS BOTONES DE INTERRUPCION
    BSF     TRISB, 0, a       ; PIN RB0 COMO ENTRADA (BOTON 1 - INT0 - ALARMA)
    BSF     TRISB, 1, a       ; PIN RB1 COMO ENTRADA (BOTON 2 - INT1 - VENTILADOR)
    BSF     TRISB, 2, a       ; PIN RB2 COMO ENTRADA (BOTON 3 - INT2 - UNIDAD °C/°F)

    ; ============================================================
    ; SECCION 4: CONFIGURAR MODULO ADC PARA EL SENSOR DE TEMPERATURA
    ; ============================================================
    MOVLW   0x0E              ; VALOR 0x0E (14 DECIMAL)
    MOVWF   ADCON1, a         ; CONFIGURA UNICAMENTE AN0 COMO ANALOGO, EL RESTO DIGITALES

    MOVLW   10100010B         ; JUSTIFICADO A LA DERECHA, FOSC/32
    MOVWF   ADCON2, a         ; GUARDA CONFIGURACION EN ADCON2

    MOVLW   00000001B         ; SELECCIONA CANAL AN0 Y ENCIENDE EL MODULO (ADON=1)
    MOVWF   ADCON0, a         ; GUARDA CONFIGURACION EN ADCON0

    ; ============================================================
    ; SECCION 5: CONFIGURAR EL TIMER0 (CRONOMETRO EXCLUSIVO PARA EL SENSOR)
    ; ============================================================
    MOVLW   10000101B         ; TMR0 ENCENDIDO, 16 BITS, RELOJ INTERNO, PRESCALER 1:64
    MOVWF   T0CON, a          ; CONFIGURA EL TEMPORIZADOR

    ; ============================================================
    ; SECCION 6: CONFIGURACION DE INTERRUPCIONES GLOBALES Y EXTERNAS
    ; ============================================================
    BCF     INTCON2, 7, a     ; HABILITA LAS RESISTENCIAS PULL-UP INTERNAS DEL PUERTO B
    BSF     INTCON2, 6, a     ; INT0 SE ACTIVA POR FLANCO DE SUBIDA (0 A 1)
    BSF     INTCON2, 5, a     ; INT1 SE ACTIVA POR FLANCO DE SUBIDA (0 A 1)
    BCF     INTCON2, 4, a     ; INT2 SE ACTIVA POR FLANCO DE BAJADA (1 A 0, BOTON A GND)

    ; LIMPIAR BANDERAS PARA EVITAR FALSAS INTERRUPCIONES AL INICIAR
    BCF     INTCON, 1, a      ; LIMPIA BANDERA DE INT0
    BCF     INTCON3, 0, a     ; LIMPIA BANDERA DE INT1
    BCF     INTCON3, 1, a     ; LIMPIA BANDERA DE INT2
    BCF     INTCON, 2, a      ; LIMPIA BANDERA DEL TIMER0

    ; HABILITAR LOS PERMISOS INDIVIDUALES DE INTERRUPCION
    BSF     INTCON, 4, a      ; HABILITA INT0 (ALARMA)
    BSF     INTCON3, 3, a     ; HABILITA INT1 (VENTILADOR)
    BSF     INTCON3, 4, a     ; HABILITA INT2 (GRADOS)
    BSF     INTCON, 5, a      ; HABILITA LA INTERRUPCION DEL TIMER0

    ; HABILITAR INTERRUPCIONES PERIFERICAS Y GLOBALES
    BSF     INTCON, 6, a      ; HABILITA INTERRUPCIONES PERIFERICAS (PEIE)
    BSF     INTCON, 7, a      ; HABILITA INTERRUPCIONES GLOBALES (GIE)

;===============================================
; BUCLE PRINCIPAL (SE EJECUTA INFINITAMENTE)
;===============================================
Loop_Principal:

    ; === MULTIPLEXADO ULTRA RAPIDO PARA ENGAÑO VISUAL DEL OJO ===

    ; APAGAR AMBOS DISPLAYS ANTES DE CAMBIAR DE NUMERO (EVITA EFECTO FANTASMA)
    BCF     LATC, 0, a        ; APAGA TRANSISTOR DE DECENAS
    BCF     LATC, 1, a        ; APAGA TRANSISTOR DE UNIDADES

    ; ENCENDER EL DISPLAY DE LAS UNIDADES
    MOVFF   PATRON_UNID, LATD ; MANDA LOS BITS DEL NUMERO AL PUERTO D
    BSF     LATC, 1, a        ; ENCIENDE EL TRANSISTOR DE LAS UNIDADES (PIN 16)
    CALL    RETARDO_MUX       ; MICRO PAUSA PARA QUE EL LED BRILLE
    BCF     LATC, 1, a        ; APAGA EL TRANSISTOR DE LAS UNIDADES

    ; ENCENDER EL DISPLAY DE LAS DECENAS
    MOVFF   PATRON_DEC, LATD  ; MANDA LOS BITS DEL NUMERO AL PUERTO D
    BSF     LATC, 0, a        ; ENCIENDE EL TRANSISTOR DE LAS DECENAS (PIN 15)
    CALL    RETARDO_MUX       ; MICRO PAUSA PARA QUE EL LED BRILLE
    BCF     LATC, 0, a        ; APAGA EL TRANSISTOR DE LAS DECENAS

    ; === FIN DEL MULTIPLEXADO ===

    ; REVISAR SI EL TIMER0 YA AVISO QUE DEBEMOS LEER EL SENSOR
    BTFSS   FLAG_LEER_ADC, 0, a ; EVALUA LA BANDERA, SALTA LA SIGUIENTE LINEA SI ES 1
    GOTO    Loop_Principal    ; SI LA BANDERA ES 0, VUELVE AL INICIO Y SIGUE MULTIPLEXANDO

    ; SI LA BANDERA ES 1, CONTINUA AQUI Y PROCEDE A LEER LA TEMPERATURA
    BCF     FLAG_LEER_ADC, 0, a ; BAJA LA BANDERA PARA ESPERAR AL PROXIMO AVISO DEL TIMER0

    ; INICIAR LA CONVERSION ANALOGO A DIGITAL (ADC)
    BSF     ADCON0, 1, a      ; PONE EN 1 EL BIT GO/DONE PARA INICIAR LA LECTURA
ESPERAR_ADC:
    BTFSC   ADCON0, 1, a      ; REVISA SI EL HARDWARE PUSO EL BIT GO/DONE EN 0
    GOTO    ESPERAR_ADC       ; SI SIGUE EN 1, SE QUEDA ATRAPADO AQUI ESPERANDO

    ; GUARDAR EL RESULTADO DE LA LECTURA
    MOVFF   ADRESL, VALOR_ADC_L ; COPIA EL BYTE BAJO DE LA LECTURA
    MOVFF   ADRESH, VALOR_ADC_H ; COPIA EL BYTE ALTO DE LA LECTURA

    ; DIVISION POR 2 (ROTACION DE BITS) PARA CONVERTIR EL VOLTAJE EN GRADOS CELSIUS
    BCF     STATUS, 0, a      ; LIMPIA EL BIT DE ACARREO (CARRY) POR SEGURIDAD
    RRCF    VALOR_ADC_H, F, a ; ROTA LOS BITS DEL BYTE ALTO HACIA LA DERECHA
    RRCF    VALOR_ADC_L, W, a ; ROTA LOS BITS DEL BYTE BAJO HACIA LA DERECHA (GUARDANDO EN W)
    MOVWF   TEMP_CELSIUS, a   ; ALMACENA LA TEMPERATURA FINAL EN CELSIUS

    ; REVISAR QUÉ UNIDAD ELIGIO EL USUARIO
    BTFSC   MODO_UNIDAD, 0, a ; SI EL MODO ESTA EN 1 (FAHRENHEIT), SALTA LA SIGUIENTE LINEA
    GOTO    CALCULAR_FAHRENHEIT ; SALTA A LA FORMULA MATEMATICA DE FAHRENHEIT

SELECCIONAR_CELSIUS:
    MOVF    TEMP_CELSIUS, W, a ; COPIA LA TEMPERATURA CELSIUS EN W
    MOVWF   TEMP_MOSTRAR, a   ; LA GUARDA EN LA VARIABLE QUE IRA A LOS DISPLAYS
    GOTO    DESCOMPONER_BCD   ; SALTA DIRECTO A SEPARAR LOS NUMEROS

CALCULAR_FAHRENHEIT:
    MOVF    TEMP_CELSIUS, W, a ; COPIA LOS GRADOS CELSIUS EN W
    MULLW   9                 ; MULTIPLICA POR 9
    MOVFF   PRODL, MATH_TEMP  ; GUARDA EL BYTE BAJO DE LA MULTIPLICACION
    MOVFF   PRODH, VALOR_ADC_H ; GUARDA EL BYTE ALTO DE LA MULTIPLICACION
    CLRF    TEMP_FAHRENHEIT, a ; LIMPIA LA VARIABLE DESTINO

RESTAR_5:
    MOVLW   5                 ; CARGA UN 5 EN W
    SUBWF   MATH_TEMP, F, a   ; RESTA 5 AL BYTE BAJO
    MOVLW   0                 ; CARGA UN 0 EN W
    SUBWFB  VALOR_ADC_H, F, a ; RESTA CON PRESTAMO AL BYTE ALTO (CORRECCION APLICADA PARA EVITAR ERRORES)
    BNC     FIN_DIV5          ; SI EL RESULTADO ES NEGATIVO (NO CARRY), TERMINO LA DIVISION
    INCF    TEMP_FAHRENHEIT, F, a ; SI ES POSITIVO, SUMA 1 AL COCIENTE
    GOTO    RESTAR_5          ; REPITE HASTA TERMINAR LA DIVISION

FIN_DIV5:
    MOVLW   32                ; CARGA 32 EN W
    ADDWF   TEMP_FAHRENHEIT, W, a ; SUMA 32 AL RESULTADO DE LA DIVISION
    MOVWF   TEMP_MOSTRAR, a   ; GUARDA EL RESULTADO FINAL EN FAHRENHEIT PARA MOSTRARLO

DESCOMPONER_BCD:
    ; METODO DE RESTAS SUCESIVAS PARA SEPARAR UNIDADES DE DECENAS
    MOVF    TEMP_MOSTRAR, W, a ; COPIA EL DATO A MOSTRAR
    CLRF    DIGITO_DEC, a     ; INICIA LAS DECENAS EN 0
BUCLE_RESTAR_10:
    MOVLW   10                ; CARGA UN 10 EN W
    SUBWF   TEMP_MOSTRAR, W, a ; LE RESTA 10 A LA TEMPERATURA
    BNC     FIN_BCD           ; SI DA NEGATIVO, SIGNIFICA QUE YA NO QUEDAN MAS DECENAS
    MOVWF   TEMP_MOSTRAR, a   ; GUARDA EL RESULTADO TEMPORAL (EL SOBRANTE)
    INCF    DIGITO_DEC, F, a  ; SUMA 1 A LAS DECENAS
    GOTO    BUCLE_RESTAR_10   ; REPITE LA RESTA

FIN_BCD:
    MOVF    TEMP_MOSTRAR, W, a ; LO QUE SOBRO DE LAS RESTAS DE 10 SON LAS UNIDADES
    MOVWF   DIGITO_UNID, a    ; GUARDA EL SOBRANTE EN LAS UNIDADES

    ; TRADUCIR NUMEROS SEPARADOS A PATRONES DE LUCES PARA EL DISPLAY
    MOVFF   DIGITO_UNID, MATH_TEMP ; ENVIA LAS UNIDADES A LA VARIABLE AUXILIAR
    CALL    DECODIFICADOR_7SEG ; LLAMA A LA SUBRUTINA DE TRADUCCION
    MOVWF   PATRON_UNID, a    ; GUARDA EL PATRON FINAL DE LAS UNIDADES (CORRECCION APLICADA)

    MOVFF   DIGITO_DEC, MATH_TEMP  ; ENVIA LAS DECENAS A LA VARIABLE AUXILIAR (FALTABA ESTO)
    CALL    DECODIFICADOR_7SEG ; LLAMA A LA SUBRUTINA DE TRADUCCION
    MOVWF   PATRON_DEC, a     ; GUARDA EL PATRON FINAL DE LAS DECENAS (CORRECCION APLICADA)

    GOTO    Loop_Principal    ; VUELVE AL INICIO A MULTIPLEXAR CON LOS DATOS NUEVOS

;===============================================
; SUBRUTINA DE MICRO RETARDO PARA EL MULTIPLEXADO (ALTA FRECUENCIA)
;===============================================
RETARDO_MUX:
    MOVLW   10                ; VALOR ENTERO MULTIPLICADOR PARA RETARDO RAPIDO
    MOVWF   DELAY1, a         ; CARGA EL VALOR EN DELAY1
LOOP_M1:
    MOVLW   166               ; SEGUNDO MULTIPLICADOR ENTERO
    MOVWF   DELAY2, a         ; CARGA EL VALOR EN DELAY2
LOOP_M2:
    DECFSZ  DELAY2, F, a      ; RESTA 1, SI ES 0 SALTA LA SIGUIENTE LINEA (USANDO EL BANCO 'a' CORRECTO)
    GOTO    LOOP_M2           ; VUELVE A LOOP_M2 HASTA QUE SEA CERO
    DECFSZ  DELAY1, F, a      ; RESTA 1, SI ES 0 SALTA LA SIGUIENTE LINEA (USANDO EL BANCO 'a' CORRECTO)
    GOTO    LOOP_M1           ; VUELVE A LOOP_M1 HASTA QUE SEA CERO
    RETURN                    ; TERMINA EL RETARDO Y REGRESA AL MULTIPLEXADO

;================================================
; RUTINA DE INTERRUPCIONES (SALTOS AL OCURRIR EVENTOS EXTERNOS O DEL TIMER)
;================================================
Rutina_ISR:
    BTFSC   INTCON, 1, a      ; ¿SE ACTIVO LA BANDERA DE INT0?
    GOTO    ISR_INT0          ; VE A LA SUBRUTINA DE INT0
    BTFSC   INTCON3, 0, a     ; ¿SE ACTIVO LA BANDERA DE INT1?
    GOTO    ISR_INT1          ; VE A LA SUBRUTINA DE INT1
    BTFSC   INTCON3, 1, a     ; ¿SE ACTIVO LA BANDERA DE INT2?
    GOTO    ISR_INT2          ; VE A LA SUBRUTINA DE INT2
    BTFSC   INTCON, 2, a      ; ¿SE ACTIVO LA BANDERA DEL TIMER0?
    GOTO    ISR_TMR0          ; VE A LA SUBRUTINA DEL TIMER0
    RETFIE  1                 ; TERMINA LA INTERRUPCION Y RETORNA EL CONTEXTO AL PROGRAMA

ISR_INT0:
    BCF     INTCON, 1, a      ; LIMPIA LA BANDERA DEL BOTON 1
    BTG     ESTADO_ALARMA, 0, a ; INVIERTE EL ESTADO DE LA VARIABLE EN RAM
    BTG     LATE, 0, a        ; INVIERTE EL ESTADO FISICO DEL LED DE ALARMA
    RETFIE  1                 ; SALE DE LA INTERRUPCION

ISR_INT1:
    BCF     INTCON3, 0, a     ; LIMPIA LA BANDERA DEL BOTON 2
    BTG     ESTADO_VENTILADOR, 0, a ; INVIERTE EL ESTADO DE LA VARIABLE EN RAM
    BTG     LATE, 1, a        ; INVIERTE EL ESTADO FISICO DEL VENTILADOR
    RETFIE  1                 ; SALE DE LA INTERRUPCION

ISR_INT2:
    BCF     INTCON3, 1, a     ; LIMPIA LA BANDERA DEL BOTON 3
    BTG     MODO_UNIDAD, 0, a ; INVIERTE LA VARIABLE DE MODO (CELSIUS O FAHRENHEIT)
    RETFIE  1                 ; SALE DE LA INTERRUPCION

ISR_TMR0:
    BCF     INTCON, 2, a      ; LIMPIA LA BANDERA DEL DESBORDAMIENTO DEL TIMER0
    BSF     FLAG_LEER_ADC, 0, a ; LEVANTA LA BANDERA PARA AVISAR AL BUCLE PRINCIPAL QUE PUEDE LEER
    RETFIE  1                 ; SALE DE LA INTERRUPCION

;===============================================
; DECODIFICADOR 7 SEGMENTOS (TRADUCE UN NUMERO A BITS PARA LEDS)
;===============================================
DECODIFICADOR_7SEG:
    MOVLW   0                 ; CARGA 0 EN W
    SUBWF   MATH_TEMP, W, a   ; RESTA EL NUMERO QUE QUEREMOS TRADUCIR MENOS 0
    BTFSC   STATUS, 2, a      ; SI EL BIT Z (CERO) ES 1, EL NUMERO ERA 0
    RETLW   00111111B         ; RETORNA EL PATRON BINARIO PARA DIBUJAR EL '0'

    MOVLW   1
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   00000110B         ; RETORNA EL PATRON BINARIO PARA EL '1'

    MOVLW   2
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01011011B         ; RETORNA EL PATRON BINARIO PARA EL '2'

    MOVLW   3
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01001111B         ; RETORNA EL PATRON BINARIO PARA EL '3'

    MOVLW   4
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01100110B         ; RETORNA EL PATRON BINARIO PARA EL '4'

    MOVLW   5
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01101101B         ; RETORNA EL PATRON BINARIO PARA EL '5'

    MOVLW   6
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01111101B         ; RETORNA EL PATRON BINARIO PARA EL '6'

    MOVLW   7
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   00000111B         ; RETORNA EL PATRON BINARIO PARA EL '7'

    MOVLW   8
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01111111B         ; RETORNA EL PATRON BINARIO PARA EL '8'

    MOVLW   9
    SUBWF   MATH_TEMP, W, a
    BTFSC   STATUS, 2, a
    RETLW   01101111B         ; RETORNA EL PATRON BINARIO PARA EL '9'

    RETLW   00000000B         ; SI HAY ERROR O SOBREPASO, RETORNA APAGADO

    END